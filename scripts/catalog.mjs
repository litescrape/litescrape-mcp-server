#!/usr/bin/env node
// Regenerates src/catalog.ts, the tools every session lists, from the Litescrape API's /api/tools.
// Usage: npm run catalog [-- saved-response.json]
import { readFile, writeFile } from 'node:fs/promises';

// The tools served without an API key; every other tool is reached through find_tools.
const ALWAYS_ON = ['google_search', 'bing_search', 'duckduckgo_search', 'google_maps'];
const FIELDS = ['name', 'title', 'description', 'method', 'path', 'keyless', 'input_schema'];

async function load(source) {
	if (source) return JSON.parse(await readFile(source, 'utf8'));
	const apiUrl = (process.env.LITESCRAPE_API_URL?.trim() || 'https://api.litescrape.com').replace(
		/\/+$/,
		'',
	);
	const response = await fetch(`${apiUrl}/api/tools?names=${ALWAYS_ON.join(',')}`);
	if (!response.ok) throw new Error(`${apiUrl}/api/tools returned HTTP ${response.status}`);
	return response.json();
}

const { tools } = await load(process.argv[2]);
const names = tools.map((tool) => tool.name);
if (names.join() !== ALWAYS_ON.join()) throw new Error(`Unexpected tools: ${names.join(', ')}`);
for (const tool of tools) {
	if (tool.keyless !== true) throw new Error(`${tool.name} is not keyless`);
}
const picked = tools.map((tool) => Object.fromEntries(FIELDS.map((field) => [field, tool[field]])));
await writeFile(
	new URL('../src/catalog.ts', import.meta.url),
	'// Generated by `npm run catalog` from the Litescrape API; do not edit.\n' +
		"import type { CatalogTool } from './tools.js';\n\n" +
		`export const ALWAYS_ON: CatalogTool[] = ${JSON.stringify(picked, null, '\t')};\n`,
);
console.log(`Wrote ${picked.length} tools to src/catalog.ts`);
